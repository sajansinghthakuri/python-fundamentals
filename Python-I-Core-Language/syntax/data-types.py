# Common Python data types
age = 28
height = 5.9
name = "Sajan"
is_learning = True
future_job = None

print(f"Age: {age}")
print(f"Height: {height}")
print(f"Name: {name}")
print(f"Learning Python: {is_learning}")
print(f"Future job: {future_job}")

# Check the types
print(type(age))
print(type(height))
print(type(name))
print(type(is_learning))
print(type(future_job))


# Different values can have different types
year = 1997
year_text = "1997"

print(year)
print(type(year))

print(year_text)
print(type(year_text))
